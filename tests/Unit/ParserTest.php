<?php

namespace Modules\SystemBase\tests\Unit;

use Modules\SystemBase\app\Services\ParserService;
use Modules\SystemBase\tests\TestCase;

class ParserTest extends TestCase
{
    protected string $env1;
    protected string $envContent;

    /**
     * @return void
     */
    public function setUp(): void
    {
        parent::setUp();

        $this->env1 = env('APP_DOMAIN');
        $this->envContent = <<<EOT
APP_DOMAIN="$this->env1"
...
APP_URL="https://\${APP_DOMAIN}/\${{unknown_var var1='4'   var_y='abc' var_z="\${{another_var_xyz a='\${APP_DOMAIN}/\${{unknown_var var1='4'   var_y='abc' var_z="\${{another_var_xyz a=''}}" }}'}}" }}"
...
LOG_STACK=daily,stderr
EOT;

    }

    /**
     * @return void
     */
    public function tearDown(): void
    {
        parent::tearDown(); // TODO: Change the autogenerated stub
    }

    /**
     *
     */
    public function test_parseEnvAndUnknownPlaceholders_true(): void
    {
        $parser = app(ParserService::class);
        $parser->allowThrowExceptions = false;
        $parser->useInlineErrors = false;
        //$parser->setPlaceholders([]);

        // parse env vars
        $result = app('system_base')->parseEnv($this->envContent);

        // parse by own parser
        $result = $parser->parse($result);

        $envContentExpected = <<<EOT
APP_DOMAIN="$this->env1"
...
APP_URL="https://$this->env1/\${{unknown_var var1='4'   var_y='abc' var_z="\${{another_var_xyz a='$this->env1/\${{unknown_var var1='4'   var_y='abc' var_z="\${{another_var_xyz a=''}}" }}'}}" }}"
...
LOG_STACK=daily,stderr
EOT;

        $this->assertTrue($result == $envContentExpected);
    }

    /**
     *
     */
    public function test_parseEnvAndKnownPlaceholders_withoutEnvVarsParsing_true(): void
    {
        $parser = app(ParserService::class);
        $parser->allowThrowExceptions = false;
        $parser->useInlineErrors = false;
        $parser->setPlaceholders([
            'another_var_xyz' => [
                'parameters' => [],
                'callback'   => function (array $placeholderParameters, array $parameters, array $recursiveData) {
                    return '123456789';
                },
            ],
        ]);

        $result = $parser->parse($this->envContent);

        $envContentExpected = <<<EOT
APP_DOMAIN="$this->env1"
...
APP_URL="https://\${APP_DOMAIN}/\${{unknown_var var1='4'   var_y='abc' var_z="123456789" }}"
...
LOG_STACK=daily,stderr
EOT;

        $this->assertTrue($result == $envContentExpected);
    }

    /**
     *
     */
    public function test_parseEnvAndKnownPlaceholders_withEnvVarsParsing_true(): void
    {
        $parser = app(ParserService::class);
        $parser->allowThrowExceptions = false;
        $parser->useInlineErrors = false;
        $parser->setPlaceholders([
            'another_var_xyz' => [
                'parameters' => [],
                'callback'   => function (array $placeholderParameters, array $parameters, array $recursiveData) {
                    return '123456789';
                },
            ],
        ]);

        // parse env vars
        $result = app('system_base')->parseEnv($this->envContent);

        // parse by own parser
        $result = $parser->parse($result);

        $envContentExpected = <<<EOT
APP_DOMAIN="$this->env1"
...
APP_URL="https://$this->env1/\${{unknown_var var1='4'   var_y='abc' var_z="123456789" }}"
...
LOG_STACK=daily,stderr
EOT;

        $this->assertTrue($result == $envContentExpected);
    }
}
